using System;
using System.Collections.Generic;
using System.IO;
using System.Text;
using DiscUtils.Iso9660;

namespace SkyCD.Plugin.Metadata.DiskImages.Tests;

/// <summary>Builds ISO 9660 images, CUE sheets, and BIN files for tests.</summary>
internal static class BinCueTestImage
{
    public const string FixtureContent = "bincue fixture content";
    public const string ReadmeContent = "readme";
    public const int UserDataSize = 2048;

    public static byte[] BuildIso()
    {
        var builder = new CDBuilder { UseJoliet = true };
        builder.AddFile(@"ROOT\DEEP\FIXTURE.TXT", Encoding.UTF8.GetBytes(FixtureContent));
        builder.AddFile(@"ROOT\README.TXT", Encoding.UTF8.GetBytes(ReadmeContent));
        using var stream = new MemoryStream();
        builder.Build(stream);
        return stream.ToArray();
    }

    /// <summary>Lays the ISO user data out in <paramref name="sectorSize"/>-byte sectors.</summary>
    public static byte[] Repack(byte[] iso, int sectorSize, int dataOffset)
    {
        if (sectorSize == UserDataSize)
        {
            return iso;
        }

        var sectorCount = iso.Length / UserDataSize;
        var result = new byte[sectorCount * sectorSize];
        for (var sector = 0; sector < sectorCount; sector++)
        {
            Buffer.BlockCopy(iso, sector * UserDataSize, result, sector * sectorSize + dataOffset, UserDataSize);
        }

        return result;
    }

    /// <summary>Writes a raw 2352-byte track preceded by empty audio sectors.</summary>
    public static byte[] WithAudioPrefix(byte[] iso, int audioSectors)
    {
        var data = Repack(iso, sectorSize: 2352, dataOffset: 16);
        var result = new byte[audioSectors * 2352 + data.Length];
        Buffer.BlockCopy(data, 0, result, audioSectors * 2352, data.Length);
        return result;
    }

    /// <summary>Formats a sector index as a CUE <c>mm:ss:ff</c> time stamp.</summary>
    public static string Stamp(int sector)
    {
        var minutes = sector / (75 * 60);
        var seconds = sector / 75 % 60;
        var frames = sector % 75;
        return $"{minutes:00}:{seconds:00}:{frames:00}";
    }

    public static string BuildSheet(IReadOnlyList<(string Mode, int Index1)> tracks,
        string? fileName = null, string? fileType = null)
    {
        var builder = new StringBuilder();
        builder.AppendLine("REM Generated by SkyCD tests");
        builder.AppendLine($"FILE \"{fileName ?? "catalog.bin"}\" {fileType ?? "BINARY"}");
        for (var index = 0; index < tracks.Count; index++)
        {
            builder.AppendLine($"  TRACK {index + 1:00} {tracks[index].Mode}");
            builder.AppendLine($"    INDEX 01 {Stamp(tracks[index].Index1)}");
        }

        return builder.ToString();
    }

    /// <summary>Writes a CUE sheet and its BIN companion into <paramref name="directory"/>.</summary>
    public static string WriteSet(string directory, string baseName, byte[] image, string sheet,
        string? imageFileName = null)
    {
        Directory.CreateDirectory(directory);
        var sheetPath = Path.Combine(directory, baseName + ".cue");
        File.WriteAllText(sheetPath, sheet);
        File.WriteAllBytes(Path.Combine(directory, imageFileName ?? baseName + ".bin"), image);
        return sheetPath;
    }
}
